import type { Analysis, MLResult } from '../types';

export function renderReport(analysis: Analysis): string {
  const meta = analysis.metadata;
  const lines: string[] = [
    `# InsyT data report — ${meta.filename}`,
    '',
    `**${meta.rows.toLocaleString()} rows · ${meta.columns} columns · ${meta.missing_cells.toLocaleString()} missing cells · ${meta.duplicate_rows.toLocaleString()} duplicate rows**`,
    '',
    '## Executive summary',
    '',
    analysis.executive_summary,
    '',
    '## Key statistics',
    '',
  ];

  for (const kpi of analysis.kpis) {
    const val = typeof kpi.value === 'number' ? kpi.value.toLocaleString(undefined, { maximumFractionDigits: 2 }) : kpi.value;
    lines.push(`- **${kpi.label}:** ${val}`);
  }

  lines.push('', '## Data quality', '', `- Missing cells: ${meta.missing_cells.toLocaleString()}.`, `- Duplicate rows: ${meta.duplicate_rows.toLocaleString()}.`);

  for (const profile of analysis.column_profiles) {
    if (profile.missing > 0) {
      lines.push(`- **${profile.name}:** ${profile.missing} missing values (${profile.missing_percent}%).`);
    }
  }

  lines.push('', '## Trends', '');
  if (analysis.trends.length > 0) {
    for (const trend of analysis.trends) {
      lines.push(`- ${trend.description} Method: ${trend.method}`);
    }
  } else {
    lines.push('No suitable date-based trend was detected.');
  }

  lines.push('', '## Potential anomalies', '', 'IQR outliers are candidates for investigation, not automatically errors or fraud.', '');
  if (analysis.anomalies.length > 0) {
    for (const item of analysis.anomalies) {
      const lower = Number(item.lower_bound).toLocaleString(undefined, { maximumFractionDigits: 2 });
      const upper = Number(item.upper_bound).toLocaleString(undefined, { maximumFractionDigits: 2 });
      lines.push(`- Row ${item.row}, **${item.column} = ${item.value}**; bounds ${lower} to ${upper} (${item.method}).`);
    }
  } else {
    lines.push('No potential numeric outliers were detected.');
  }

  lines.push('', '## Correlations', '');
  if (analysis.correlations.length > 0) {
    for (const item of analysis.correlations) {
      lines.push(`- ${item.description}`);
    }
  } else {
    lines.push('No notable pairwise correlations were detected.');
  }

  lines.push('', '## Findings', '');
  if (analysis.findings.length > 0) {
    for (const item of analysis.findings) {
      lines.push(`### ${item.title}\n\n${item.description}\n\n- Evidence: \`${JSON.stringify(item.evidence)}\`\n- Method: ${item.method}\n- Suggested next step: ${item.next_step}\n`);
    }
  } else {
    lines.push('No notable findings met the analysis thresholds.', '');
  }

  lines.push('## Recommendations', '');
  analysis.recommendations.forEach((text, index) => {
    lines.push(`${index + 1}. ${text}`);
  });

  lines.push('', '## Dataset profile', '', '| Field | Type | Missing | Unique |', '|---|---|---:|---:|');
  for (const item of analysis.column_profiles) {
    lines.push(`| ${item.name} | ${item.type} | ${item.missing} (${item.missing_percent}%) | ${item.unique} |`);
  }

  lines.push(
    '',
    '## Limitations',
    '',
    'Outliers are statistical flags and require context. Correlation describes association and does not establish causation. Period comparisons describe observed values, not a sustained or causal trend. Results depend on the supplied rows and inferred types.',
    '',
    '*Generated by InsyT.*'
  );

  return lines.join('\n');
}

export function renderMLSection(result: MLResult): string {
  const metrics = result.metrics;
  const counts = result.counts;
  const splitPct = Math.round(result.configuration.test_size * 100);

  const lines: string[] = [
    '',
    '## Predictive intelligence — Random Forest regression',
    '',
    `- Target: **${result.target}**.`,
    `- Input features: ${result.features.join(', ')}.`,
    `- Usable rows: ${counts.usable_rows}; removed for missing target: ${counts.target_rows_removed}.`,
    `- Training rows: ${counts.training_rows}; held-out test rows: ${counts.test_rows}.`,
    `- Model: RandomForestRegressor with ${result.configuration.n_estimators} trees; random split ${splitPct}%; random state ${result.configuration.random_state}.`,
    `- Test MAE: ${metrics.mae.toFixed(4)}.`,
    `- Test RMSE: ${metrics.rmse.toFixed(4)}.`,
  ];

  if (metrics.r2 !== null) {
    lines.push(`- Test R²: ${metrics.r2.toFixed(4)}.`);
  } else {
    lines.push('- Test R²: not meaningful for this test sample.');
  }

  lines.push('', '### Feature importance', '', 'Importance describes model reliance and does not establish causation.', '');
  if (result.feature_importance.length > 0) {
    for (const item of result.feature_importance) {
      lines.push(`- ${item.feature}: ${item.importance.toFixed(4)}`);
    }
  } else {
    lines.push('No feature importance could be calculated.');
  }

  lines.push(
    '',
    '### Held-out predictions',
    '',
    `The downloadable CSV contains ${result.prediction_count} held-out predictions. The response preview is limited to ${result.predictions.length} rows.`,
    '',
    '### Predictive limitations',
    ''
  );

  for (const warning of result.warnings) {
    lines.push(`- ${warning}`);
  }
  lines.push(
    '- MAE, RMSE, and R² are test-set metrics; R² may be negative and can be unreliable with a small test sample.',
    '- Random splitting is ordinary regression evaluation, not time-series forecasting. Predictive performance depends on data representativeness.'
  );

  return lines.join('\n');
}
