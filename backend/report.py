"""Evidence-based Markdown report rendering."""


def render_report(analysis: dict) -> str:
    meta = analysis["metadata"]
    lines = [f"# InsyT data report — {meta['filename']}", "",
             f"**{meta['rows']:,} rows · {meta['columns']} columns · {meta['missing_cells']:,} missing cells · {meta['duplicate_rows']:,} duplicate rows**",
             "", "## Executive summary", "", analysis["executive_summary"], "", "## Key statistics", ""]
    lines.extend(f"- **{kpi['label']}:** {kpi['value']:,}" if isinstance(kpi["value"], int) else f"- **{kpi['label']}:** {kpi['value']}" for kpi in analysis["kpis"])
    lines += ["", "## Data quality", "", f"- Missing cells: {meta['missing_cells']:,}.", f"- Duplicate rows: {meta['duplicate_rows']:,}."]
    for profile in analysis["column_profiles"]:
        if profile["missing"]:
            lines.append(f"- **{profile['name']}:** {profile['missing']} missing values ({profile['missing_percent']}%).")
    lines += ["", "## Trends", ""]
    lines += [f"- {trend['description']} Method: {trend['method']}" for trend in analysis["trends"]] or ["No suitable date-based trend was detected."]
    lines += ["", "## Potential anomalies", "", "IQR outliers are candidates for investigation, not automatically errors or fraud.", ""]
    lines += [f"- Row {item['row']}, **{item['column']} = {item['value']}**; bounds {item['lower_bound']} to {item['upper_bound']} ({item['method']})." for item in analysis["anomalies"]] or ["No potential numeric outliers were detected."]
    lines += ["", "## Correlations", ""]
    lines += [f"- {item['description']}" for item in analysis["correlations"]] or ["No notable pairwise correlations were detected."]
    lines += ["", "## Findings", ""]
    lines += [f"### {item['title']}\n\n{item['description']}\n\n- Evidence: `{item['evidence']}`\n- Method: {item['method']}\n- Suggested next step: {item['next_step']}\n" for item in analysis["findings"]] or ["No notable findings met the analysis thresholds.", ""]
    lines += ["## Recommendations", ""] + [f"{index}. {text}" for index, text in enumerate(analysis["recommendations"], 1)]
    lines += ["", "## Dataset profile", "", "| Field | Type | Missing | Unique |", "|---|---|---:|---:|"]
    lines += [f"| {item['name']} | {item['type']} | {item['missing']} ({item['missing_percent']}%) | {item['unique']} |" for item in analysis["column_profiles"]]
    lines += ["", "## Limitations", "", "Outliers are statistical flags and require context. Correlation describes association and does not establish causation. Period comparisons describe observed values, not a sustained or causal trend. Results depend on the supplied rows and inferred types.", "", "*Generated by InsyT.*"]
    return "\n".join(lines)


def render_ml_section(result: dict) -> str:
    metrics = result["metrics"]
    counts = result["counts"]
    lines = ["", "## Predictive intelligence — Random Forest regression", "",
             f"- Target: **{result['target']}**.", f"- Input features: {', '.join(result['features'])}.",
             f"- Usable rows: {counts['usable_rows']}; removed for missing target: {counts['target_rows_removed']}.",
             f"- Training rows: {counts['training_rows']}; held-out test rows: {counts['test_rows']}.",
             f"- Model: RandomForestRegressor with {result['configuration']['n_estimators']} trees; random split {result['configuration']['test_size']:.0%}; random state {result['configuration']['random_state']}.",
             f"- Test MAE: {metrics['mae']:.4g}.", f"- Test RMSE: {metrics['rmse']:.4g}."]
    lines.append(f"- Test R²: {metrics['r2']:.4g}." if metrics["r2"] is not None else "- Test R²: not meaningful for this test sample.")
    lines += ["", "### Feature importance", "", "Importance describes model reliance and does not establish causation.", ""]
    lines += [f"- {item['feature']}: {item['importance']:.4f}" for item in result["feature_importance"]] or ["No feature importance could be calculated."]
    lines += ["", "### Held-out predictions", "", f"The downloadable CSV contains {result['prediction_count']} held-out predictions. The response preview is limited to {len(result['predictions'])} rows.", "", "### Predictive limitations", ""]
    lines += [f"- {warning}" for warning in result["warnings"]]
    lines += ["- MAE, RMSE, and R² are test-set metrics; R² may be negative and can be unreliable with a small test sample.",
              "- Random splitting is ordinary regression evaluation, not time-series forecasting. Predictive performance depends on data representativeness."]
    return "\n".join(lines)
